"use strict";
import { writeSync } from "node:fs";
function $mini_number_to_text(value) {
    if (typeof value !== "number" || !Number.isSafeInteger(value)) return "";
    return String(value);
}
function join(left, right) {
    return (left + right);
    return 0;
}
